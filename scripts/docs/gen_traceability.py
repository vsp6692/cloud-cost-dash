#!/usr/bin/env python3
"""Builds docs/planning/TRACEABILITY_MATRIX.md and ACCEPTANCE_MATRIX.md from the PRD and the phase docs.
Requirement -> delivering phase(s) -> planned code location -> phase requirements -> test cases -> acceptance criteria -> docs.
Re-run after editing the PRD or phase docs: python3 scripts/docs/gen_traceability.py ."""
import os, re, sys, glob, collections
root = sys.argv[1] if len(sys.argv) > 1 else "."
prd = open(os.path.join(root, "docs/product/PRD.md")).read()

CODE = {"TEN":"internal/tenants","IAM":"internal/identity, internal/authz","CON":"internal/connectors","AWS":"providers/aws","GCP":"providers/gcp",
 "AZR":"providers/azure","IMP":"providers/generic, internal/billing","NRM":"internal/billing","ING":"internal/billing, apps/worker","ANL":"internal/analytics",
 "DSH":"apps/web, internal/dashboards","ALC":"internal/allocation","BUD":"internal/forecasting, internal/alerts","FIN":"internal/finance","RES":"internal/inventory",
 "TEL":"internal/inventory","REC":"internal/recommendations, sdk/recommendation","AI":"internal/ai","AUD":"internal/audit","NTF":"internal/alerts",
 "OPS":"deploy/, internal/platform","SDK":"sdk/","SEC":"cross-cutting","ACC":"internal/billing, internal/finance","PERF":"cross-cutting","SCL":"cross-cutting",
 "AVL":"deploy/","FRS":"internal/billing","OBS":"internal/platform","A11Y":"apps/web","I18N":"apps/web","PRIV":"cross-cutting","MNT":"CI","CMP":"api/, sdk/",
 "PORT":"CI","LIC":"compliance/, .github/workflows"}
DOC = {"TEN":"architecture/TENANCY.md","IAM":"security/AUTHORIZATION_MODEL.md","CON":"providers/README.md","AWS":"providers/AWS.md","GCP":"providers/GCP.md",
 "AZR":"providers/AZURE.md","IMP":"providers/GENERIC_IMPORTS.md","NRM":"architecture/FOCUS_NORMALIZATION.md","ING":"architecture/INGESTION_PIPELINE.md",
 "ANL":"architecture/ANALYTICS_ADAPTERS.md","DSH":"phases/phase-14/DESIGN.md","ALC":"architecture/ALLOCATION_ENGINE.md","BUD":"architecture/FORECASTING_ANOMALIES.md",
 "FIN":"architecture/FINANCE_RECONCILIATION.md","RES":"architecture/RESOURCE_INVENTORY.md","TEL":"architecture/RESOURCE_INVENTORY.md","REC":"architecture/RECOMMENDATION_ENGINE.md",
 "AI":"architecture/LLM_SECURITY.md","AUD":"architecture/DATABASE_SCHEMA.md","NTF":"phases/phase-32/DESIGN.md","OPS":"operations/README.md","SDK":"contracts/PROVIDER_SDK.md",
 "LIC":"legal/LICENSE_COMPLIANCE.md"}

reqs = []  # (id, text, prd_phase)
for m in re.finditer(r"^\| (FR-[A-Z]+-\d{3}) \| (.+?) \| [MSC] \| ([^|]+) \|", prd, re.M):
    reqs.append((m.group(1), m.group(2), m.group(3).strip()))
for m in re.finditer(r"^\| (NFR-[A-Z0-9]+-\d{3}) \| [^|]+ \| (.+?) \| ([^|]+) \|", prd, re.M):
    reqs.append((m.group(1), m.group(2), m.group(3).strip()))

ph_req = collections.defaultdict(set); ph_tc = collections.defaultdict(set); ph_ac = collections.defaultdict(set); phases_with_docs=set()
for d in sorted(glob.glob(os.path.join(root, "docs/phases/phase-*"))):
    p = d[-2:]
    def rd(n):
        f = os.path.join(d, n); return open(f).read() if os.path.exists(f) else ""
    R, T, A = rd("REQUIREMENTS.md"), rd("TEST_PLAN.md"), rd("ACCEPTANCE.md")
    if R: phases_with_docs.add(p)
    for line in R.splitlines():
        rid = re.search(rf"P{p}-R\d+", line)
        if rid:
            for x in set(re.findall(r"(?:N?FR|NFR)-[A-Z0-9]+-\d{3}", line)): ph_req[x].add(rid.group(0))
    for line in T.splitlines():
        tid = re.search(rf"P{p}-TC\d+", line)
        if tid:
            for x in set(re.findall(r"(?:N?FR|NFR)-[A-Z0-9]+-\d{3}", line)): ph_tc[x].add(tid.group(0))
            for r in set(re.findall(rf"P{p}-R\d+", line)):
                for k,v in ph_req.items():
                    if r in v: ph_tc[k].add(tid.group(0))
    for line in A.splitlines():
        aid = re.search(rf"P{p}-AC\d+", line)
        if aid:
            for x in set(re.findall(r"(?:N?FR|NFR)-[A-Z0-9]+-\d{3}", line)): ph_ac[x].add(aid.group(0))
            for r in set(re.findall(rf"P{p}-R\d+", line)):
                for k,v in ph_req.items():
                    if r in v: ph_ac[k].add(aid.group(0))

def short(s, n): return ", ".join(sorted(s)[:n]) + (f" (+{len(s)-n})" if len(s) > n else "")
out = ["# Traceability Matrix", "",
"Generated by `scripts/docs/gen_traceability.py` from the PRD and the phase docs. **Do not edit by hand.** Re-run after changes.",
"", "Chain: **PRD requirement → delivering phase → planned code location → phase requirements → test cases → acceptance criteria → design doc**. Code locations are *planned*: no code exists yet. Test status lives in each phase's `TEST_RESULTS.md` (all NOT RUN).", "",
f"Phase docs found: {len(phases_with_docs)}/40.", "",
"| PRD ID | Requirement (abridged) | Phase(s) | Planned code | Phase reqs | Test cases | Acceptance | Design doc |", "|---|---|---|---|---|---|---|---|"]
gaps = []
for rid, text, ph in reqs:
    pre = rid.split("-")[1]
    t = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text); t = (t[:90] + "…") if len(t) > 90 else t
    pr, tc, ac = ph_req.get(rid, set()), ph_tc.get(rid, set()), ph_ac.get(rid, set())
    if not pr or not tc: gaps.append(rid)
    doc = DOC.get(pre); docl = f"[{doc}](../{doc})" if doc else "—"
    out.append(f"| {rid} | {t} | {ph} | `{CODE.get(pre,'TBD')}` | {short(pr,4) or '**GAP**'} | {short(tc,4) or '**GAP**'} | {short(ac,3) or '—'} | {docl} |")
out += ["", f"## Gaps ({len(gaps)})", "Requirements with no phase requirement or no test case referencing them. Each must be closed before its phase is accepted:", "", (", ".join(gaps) if gaps else "None.")]
open(os.path.join(root, "docs/planning/TRACEABILITY_MATRIX.md"), "w").write("\n".join(out) + "\n")

# Acceptance matrix: product AC / journeys -> phases
acs = re.findall(r"- \*\*(AC-\d+) \(([^)]+)\):\*\* (.+)", prd)
jrn = re.findall(r"^\| (UJ-\d+) \| \*\*(.+?)\*\* \|", prd, re.M)
refs = collections.defaultdict(set)
for d in sorted(glob.glob(os.path.join(root, "docs/phases/phase-*"))):
    p = d[-2:]
    for f in glob.glob(os.path.join(d, "*.md")):
        for x in set(re.findall(r"\b(AC-\d{2}|UJ-\d{2})\b", open(f).read())): refs[x].add(p)
A = ["# Acceptance Matrix", "", "Generated by `scripts/docs/gen_traceability.py`. Product-level acceptance criteria (PRD §7) and user journeys (PRD §4), mapped to the phases that reference them. Status remains **NOT VERIFIED** until a phase's TEST_RESULTS records real executions.", "",
     "## Product acceptance criteria", "", "| ID | Area | Criterion | Phases referencing | Final gate | Status |", "|---|---|---|---|---|---|"]
for i, area, txt in acs:
    A.append(f"| {i} | {area} | {txt} | {', '.join(sorted(refs.get(i, []))) or '—'} | 38 | NOT VERIFIED |")
A += ["", "## User journeys (Playwright E2E)", "", "| ID | Journey | Phases referencing | Status |", "|---|---|---|---|"]
for i, name in jrn:
    A.append(f"| {i} | {name} | {', '.join(sorted(refs.get(i, []))) or '—'} | NOT VERIFIED |")
A += ["", "## Phase acceptance status", "", "| Phase | Acceptance doc | Status |", "|---|---|---|"]
for n in range(1, 41):
    p = f"{n:02d}"; f = f"docs/phases/phase-{p}/ACCEPTANCE.md"
    A.append(f"| {p} | [{f.split('/',1)[1]}](../phases/phase-{p}/ACCEPTANCE.md) | {'NOT STARTED' if os.path.exists(os.path.join(root,f)) else 'DOC MISSING'} |")
open(os.path.join(root, "docs/planning/ACCEPTANCE_MATRIX.md"), "w").write("\n".join(A) + "\n")
print(f"{len(reqs)} PRD requirements, {len(phases_with_docs)} phases with docs, {len(gaps)} gaps")
